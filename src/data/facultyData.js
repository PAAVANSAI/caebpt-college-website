/**
 * Helper utility to find a faculty member by ID or slug
 */
export function getFacultyById(id) {
  if (!id) return null;
  const cleanId = id.toLowerCase().trim();
  return (
    facultyData.find(
      (f) =>
        f.id.toLowerCase() === cleanId ||
        f.id.replace(/^fac-/, '').toLowerCase() === cleanId ||
        cleanId.includes(f.id.toLowerCase())
    ) || null
  );
}

/**
 * Helper utility to get all faculty members belonging to a department
 */
export function getFacultyByDept(deptId) {
  if (!deptId) return [];
  const cleanDept = deptId.toLowerCase().trim();
  return facultyData.filter(
    (f) =>
      f.deptId.toLowerCase() === cleanDept ||
      f.deptSlug?.toLowerCase() === cleanDept ||
      (cleanDept === 'pfe' && f.deptId === 'apfe') ||
      (cleanDept === 'apfe' && f.deptId === 'pfe')
  );
}
